import {expect,test,type Locator} from '@playwright/test';
import {mkdir} from 'node:fs/promises';

const folder='work/screenshots/ingredient-layout';
test.use({browserName:'webkit',channel:'',isMobile:true,hasTouch:true,deviceScaleFactor:3});
for(const width of [320,375,390,430])for(const language of ['en','zh']){
  test(`ingredient journal add and edit at ${width}px in ${language}`,async({page})=>{
    await page.setViewportSize({width,height:844});
    await page.goto('/pantry');
    await page.evaluate(async ({language,width})=>{
      const {db}=await import('/src/domain.ts');
      await db.settings.put({key:'language',value:language});
      await db.settings.put({key:'theme',value:({320:'olive',375:'apricot',390:'misty',430:'lavender'})[width]!});
    },{language,width});
    await page.reload();
    await page.locator('.pantry-fab').tap();await page.locator('.pantry-add-ingredient').tap();
    const editor=page.locator('.ingredient-journal'),conversion=page.locator('.journal-conversion');
    const basics=editor.locator('.ingredient-basics');
    const secondary=basics.locator('.ingredient-secondary-fields');
    const alias=secondary.locator('[name=nameZh]'),brand=secondary.locator('[name=brand]');
    const expectColumns=async()=>{
      const boxes=await secondary.locator('label').evaluateAll(labels=>labels.map(label=>{
        const r=label.getBoundingClientRect();
        return {x:r.x,y:r.y,right:r.right,width:r.width,overflow:label.scrollWidth-label.clientWidth};
      }));
      expect(boxes).toHaveLength(2);
      expect(boxes[0].y).toBe(boxes[1].y);
      expect(boxes[0].right).toBeLessThan(boxes[1].x);
      expect(Math.abs(boxes[0].width-boxes[1].width)).toBeLessThan(1);
      expect(boxes.every(b=>b.overflow<=1)).toBe(true);
    };
    const capture=async(name:string,region?:Locator)=>{
      if(language==='zh'&&(name==='12-long-content'?width===320:width===390)){
        await mkdir(folder,{recursive:true});
        await page.evaluate(()=>document.fonts.ready.then(()=>true));
        await (region??page).screenshot({path:folder+'/'+name+'.png',scale:'device',caret:'initial'});
      }
    };
    await expect(editor.locator('select')).toHaveCount(0);
    const servingValues=await editor.locator('.serving-unit-settings .serving-unit-value').evaluateAll(values=>values.map(value=>value.getBoundingClientRect().top));
    expect(servingValues).toHaveLength(2);
    expect(servingValues[0]).toBe(servingValues[1]);
    await expect(basics.getByRole('heading')).toHaveCount(1);
    await expect(secondary.locator('svg')).toHaveCount(0);
    await expectColumns();
    await capture('01-add-blank');
    await capture('basic-empty',basics);
    await editor.locator('.form-actions .primary').tap();
    await expect(editor.locator('[name=name]')).toBeFocused();
    const name=width===320?'烘焙用黑巧克力 Dark Chocolate with toasted almonds and sea salt':'黑巧克力 Dark Chocolate';
    const nameInput=editor.locator('[name=name]');
    await nameInput.fill(name);
    await capture('05-inline-name');
    await nameInput.press('Enter');
    await capture('04-brand-absent');
    const aliases=width===320?'Cacao noir artisanal, 烘焙用苦甜黑巧克力':'Cacao, 黑巧';
    const brandName=width===320?'Mélange 烘焙工坊 • Atelier de chocolat artisanal':'Atelier Cacao';
    await brand.fill(brandName);
    await brand.press('Enter');
    await expectColumns();
    await brand.fill('');
    await alias.fill(aliases);
    await alias.press('Enter');
    await expectColumns();
    await capture('one-optional-filled');
    await brand.fill(brandName);
    await brand.press('Enter');
    await expectColumns();
    if(width===320){
      const wraps=await secondary.locator('.draft-name-line > span').evaluateAll(nodes=>nodes.map(n=>n.getBoundingClientRect().height>parseFloat(getComputedStyle(n).lineHeight)*1.5));
      expect(wraps).toEqual([true,true]);
    }
    const chip=editor.locator('.ingredient-tag-choices [aria-pressed]').first();
    await chip.tap();
    await expect(chip).toHaveAttribute('aria-pressed','true');
    await expect(chip.locator('svg')).toHaveCount(0);
    await capture('06-tags');
    await capture('basic-filled',basics);
    await capture('12-long-content');
    const tail=basics.locator('.ingredient-tag-tail button');
    const lastTag=await tail.first().boundingBox(),more=await tail.last().boundingBox();
    expect(Math.abs(more!.y+more!.height/2-lastTag!.y-lastTag!.height/2)).toBeLessThan(1);
    expect(more!.x-lastTag!.x-lastTag!.width).toBeCloseTo(5,0);
    await tail.last().tap();
    await page.locator('.ingredient-tag-manager .modal-head button').tap();
    await expect(chip).toHaveAttribute('aria-pressed','true');
    const method=editor.locator('.ingredient-basis-choice button');
    const menu=editor.getByRole('menu');
    await method.tap();
    await expect(menu.getByRole('menuitemradio')).toHaveCount(2);
    await capture('07-basis-menu');
    await menu.locator('[data-unit=serving]').tap();
    await editor.locator('[name=servingGrams]').fill('15');
    await method.tap();
    await menu.locator('[data-unit="100g"]').tap();
    const ref=editor.locator('[name=referenceAmount]');
    const amount=editor.locator('.ingredient-amount').filter({has:page.locator('[name=referenceAmount]')});
    const ink=amount.locator('.journal-amount-ink');
    await ref.scrollIntoViewIfNeeded();
    const prefix=await editor.locator('.ingredient-reference-phrase > span').boundingBox();
    const input=await ref.boundingBox(),unit=await amount.getByRole('button').boundingBox();
    expect(input!.x-prefix!.x-prefix!.width).toBeCloseTo(5,0);
    expect(unit!.x-input!.x-input!.width).toBeCloseTo(4,0);
    expect(unit!.x+unit!.width-prefix!.x).toBeLessThan(130);
    await expect(ink).toHaveCSS('width','56px');
    await capture('08-reference');
    const before=await ink.boundingBox();
    expect(before!.width).toBe(56);
    await ref.tap();
    await ref.fill('32.5');
    await expect(ref).toHaveCSS('border-top-width','0px');
    await expect(ink).toHaveCSS('width','56px');
    expect(await ink.boundingBox()).toMatchObject({x:before!.x,width:56});
    await capture('09-reference-editing');
    await ref.press('Enter');
    await expect(ink).toHaveCSS('width','56px');
    expect((await ink.boundingBox())!.width).toBe(56);
    await amount.getByRole('button').tap();
    await expect(menu.getByRole('menuitemradio')).toHaveText(['g','mL']);
    await expect(menu.locator('svg')).toHaveCount(0);
    await capture('10-unit-menu');
    await menu.locator('[data-unit=mL]').tap();
    await editor.locator('[name=calories]').fill('120');
    const protein=editor.locator('[name=protein]');
    await protein.fill('-1');
    await editor.locator('.form-actions .primary').tap();
    await expect(editor).toBeVisible();
    expect(await protein.evaluate((input:HTMLInputElement)=>input.validity.rangeUnderflow)).toBe(true);
    expect(await page.evaluate(async()=> (await import('/src/domain.ts')).db.ingredients.count())).toBe(0);
    await protein.fill('8');
    await editor.locator('[name=carbs]').fill('20');
    await editor.locator('[name=fat]').fill('3');
    await editor.locator('[name=fat]').press('Enter');
    await editor.locator('.nutrition-fields').evaluate(el=>el.scrollIntoView({block:'center'}));
    await expect(editor.locator('[name=fat]')).toBeInViewport();
    await capture('11-nutrition');
    await editor.locator('.ingredient-unit-add').tap();
    await conversion.locator('[name=conversionName]').fill('piece');
    await conversion.locator('[name=conversionQuantity]').fill('1');
    await conversion.locator('[name=conversionAmount]').fill('12');
    await conversion.locator('[name=conversionAmount]').press('Enter');
    await expect(editor.locator('.journal-unit-summary small')).toHaveText('1 piece ≈ 12 mL');
    await editor.locator('.pantry-editor-body').evaluate(el=>el.scrollTop=0);
    await capture('02-add-filled');
    await editor.locator('.form-actions .primary').tap();
    await expect(editor).toHaveCount(0);
    const records=()=>page.evaluate(async()=>{const {db}=await import('/src/domain.ts');return db.ingredients.toArray()});
    const saved=await records();
    expect(saved).toHaveLength(1);
    expect(saved[0]).toMatchObject({name,brand:brandName,aliases:aliases.split(', '),referenceUnit:'mL',referenceAmount:32.5,calories:120,protein:8,carbs:20,fat:3,
      consumptionUnit:{quantity:1,name:'piece',amount:12,unit:'mL'}});
    const open=()=>page.locator('[data-user-food-id] .ingredient-name').tap();
    await open();
    await expectColumns();
    await capture('03-edit');
    await nameInput.fill('Discard this change');
    await amount.getByRole('button').tap();
    await expect(menu.locator('[data-unit=mL]')).toHaveAttribute('aria-checked','true');
    await menu.locator('[data-unit=g]').tap();
    await chip.tap();
    await ref.fill('1000');
    await editor.locator('.form-actions button').first().tap();
    expect(await records()).toEqual(saved);
    await open();
    await ref.fill('19.599999999999998');
    await ref.press('Enter');
    await expect(ref).toHaveValue('19.6');
    await ref.tap();
    await ref.press('Enter');
    await editor.locator('.form-actions .primary').tap();
    const edited=await records();
    expect(edited).toHaveLength(1);
    expect(edited[0]).toMatchObject({id:saved[0].id,referenceAmount:19.599999999999998,revision:saved[0].revision+1});
    await page.locator('.pantry-fab').tap();await page.locator('.pantry-add-ingredient').tap();
    await nameInput.fill('Unsaved new ingredient');
    await editor.locator('.form-actions button').first().tap();
    expect(await records()).toEqual(edited);
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  });
}
