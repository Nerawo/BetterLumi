import { test, expect } from '@playwright/test';
const output='./work/screenshots/';
test.use({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
test('compact food dialog saves unknowns, keeps a single scroll region and collapses recipe changes',async({page})=>{
 await page.goto('/today');
 await page.getByRole('button',{name:'添加餐食',exact:true}).click();
 const dialog=page.locator('.add-food-modal');
 await expect(dialog).toBeVisible();
 await expect(dialog.locator(".source-tabs button")).toHaveCount(3);
 const tabs=await dialog.locator('.source-tabs button').first().boundingBox();
 expect(tabs!.height).toBeGreaterThanOrEqual(44);
 const tabBoxes=await dialog.locator('.source-tabs button').evaluateAll(es=>es.map(e=>e.getBoundingClientRect().y));
 expect(new Set(tabBoxes).size).toBe(1);
 const dates=await dialog.locator('.meal-date-row label').evaluateAll(es=>es.map(e=>e.getBoundingClientRect().y));
 expect(dates[0]).toBe(dates[1]);
 await dialog.locator('input:not([type])').fill('手机测试餐');
 await dialog.locator('.nutrition-fields input').first().fill('420');
 await expect(dialog.locator('.meal-extras')).not.toHaveAttribute('open');
 const save=dialog.locator('.add-food-footer .primary');
 expect((await save.boundingBox())!.y+(await save.boundingBox())!.height).toBeLessThanOrEqual(844);
 await page.screenshot({path:output+'移动精修-添加饮食.png'});
 await save.click();
 await expect(dialog).toHaveCount(0);
 await expect(page.locator('.meal-row')).toContainText('手机测试餐');
 await page.reload();
 await expect(page.locator('.meal-row')).toContainText('手机测试餐');
 const record=await page.evaluate(async()=>{const d=await import('/src/domain.ts');return(await d.foodLogs.toArray())[0]});
 expect(record.nutrition.protein).toBeNull();
 expect(record.nutrition.calories).toBe(420);
 await expect(page.locator('.today-progress')).not.toContainText('无适用比较');
 await expect(page.locator('.today-progress .progress-track')).toHaveCount(0);
 await expect(page.locator('.meal-card .nutrition-strip')).toHaveCount(0);
 const recipe=await page.evaluate(async()=>{const d=await import('/src/domain.ts');const r={...d.stamp(),name:'测试食谱',servings:1,lines:[{name:'燕麦',quantity:30,unit:'g',nutrition:{calories:120,protein:null,carbs:null,fat:null}}],instructions:'煮熟。',stickyNote:''};await d.recipes.put(r);return r.id;});
 await page.goto('/recipes/'+recipe);
 await page.locator('.recipe-detail-modal .detail-toolbar .primary').click();
 await expect(dialog).toBeVisible();
 await expect(dialog.locator('.meal-advanced')).not.toHaveAttribute('open');
 await expect(dialog.locator('.recipe-line')).not.toBeVisible();
 await dialog.locator('.meal-advanced > summary').click();
 await expect(dialog.locator('.recipe-line')).toBeVisible();
 await dialog.locator('.meal-extras > summary').click();
 await dialog.locator('textarea').fill('这次备注');
 await dialog.locator('.add-food-scroll').evaluate(e=>e.scrollTop=e.scrollHeight);
 await expect(save).toBeVisible();
 expect(await dialog.evaluate(e=>e.scrollHeight<=e.clientHeight)).toBe(true);
 await page.setViewportSize({width:390,height:460});
 await expect(save).toBeInViewport();
 await save.click();
 const original=await page.evaluate(async id=>{const d=await import('/src/domain.ts');return d.recipes.get(id)},recipe);
 expect(original!.lines[0].quantity).toBe(30);
});

