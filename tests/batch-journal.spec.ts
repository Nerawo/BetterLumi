import {test,expect,type Locator} from '@playwright/test';
import {mkdir} from 'node:fs/promises';

test.use({browserName:'webkit',channel:'',isMobile:true,hasTouch:true,deviceScaleFactor:3});
for(const width of [320,375,390,430])for(const language of ['zh','en'])test(`batch journal mixed sources and correction at ${width}px ${language}`,async({page})=>{
  const folder='work/screenshots/batch-results';
  await mkdir(folder,{recursive:true});
  await page.setViewportSize({width,height:844});
  await page.goto('/recipes');
  const fixture=await page.evaluate(async({width,language})=>{
    const d=await import('/src/domain.ts');
    const {FoodStorage}=await import('/src/food-storage.ts');
    await d.db.settings.put({key:'language',value:language});
    await d.db.settings.put({key:'theme',value:({320:'olive',375:'apricot',390:'misty',430:'lavender'})[width]!});
    const nutrition={calories:380,protein:12,carbs:61,fat:7};
    const oats={...d.stamp(),name:'燕麦片 Rolled Oats',brand:'',nameZh:'',basis:'100g' as const,servingGrams:null,...nutrition,
      consumptionUnit:{quantity:1,name:'勺',amount:25,unit:'g' as const}};
    await d.db.ingredients.put(oats);
    const lines=[{ingredientId:oats.id,name:oats.name,quantity:100,unit:'g',nutrition}];
    const recipe={...d.stamp(),name:'苹果肉桂烤燕麦 Apple Cinnamon Baked Oats',servings:2,lines,instructions:'',stickyNote:''};
    await d.recipes.put(recipe);
    const id=d.stamp().id;
    await new FoodStorage().makeBatch({id,operationId:d.stamp().id,name:'苹果泥',preparedOn:d.localDate(),cookedYieldGrams:350,
      ingredients:[{source:'pantry',line:{...lines[0],name:'苹果',nutrition:{calories:120,protein:1,carbs:29,fat:0}}}]});
    return {recipe:recipe.id,stock:id,pantry:oats.id};
  },{width,language});
  await page.reload();
  await page.locator('#recipes-storage-tab').tap();
  await page.locator('.storage-make-trigger').tap();
  const modal=page.locator('.storage-make-modal');
  const shot=async(name:string,area:Locator=modal)=>{
    if(language==='zh'&&(name==='long-320'?width===320:width===390)){
      await page.evaluate(()=>document.fonts.ready.then(()=>true));
      await area.screenshot({path:folder+'/'+(name==='long-320'?width+'-':'')+name+'.png',scale:'device',caret:'initial'});
    }
  };
  const headings=modal.locator('h3 .journal-heading');
  await expect(headings).toHaveText(language==='zh'?['批次结果']:['Batch Results']);
  await expect(modal.locator('textarea')).toHaveCount(0);
  await shot('01-blank');
  await shot('empty-note',modal.locator('.batch-note-action'));
  await modal.locator('[name=batchName]').fill('周末燕麦');
  await modal.locator('.batch-review > summary').tap();await modal.locator('.ingredient-add-trigger').tap();
  await page.locator('[data-ingredient-id="'+fixture.pantry+'"]').tap();
  await modal.locator('[name=cookedYieldGrams]').fill('200');
  await modal.locator('[name=cookedYieldGrams]').press('Enter');
  await shot('scratch-filled');
  await modal.locator('.form-actions button').first().tap();
  await page.locator('.storage-make-trigger').tap();
  await modal.locator('.date-field-trigger').tap();
  const day=page.locator('[data-jump-date]:enabled').first();
  const selectedDate=await day.getAttribute('data-jump-date');
  await day.tap();
  await expect(modal.locator('[type=date]')).toHaveValue(selectedDate!);
  const weight=modal.locator('[name=cookedYieldGrams]');
  const weightSection=modal.locator('section').filter({has:page.locator('[name=cookedYieldGrams]')});
  const ink=weightSection.locator('.journal-amount-ink');
  expect((await ink.boundingBox())!.width).toBe(56);
  await shot('09-weight-empty',weightSection);
  await modal.locator('.recipe-selection-trigger').tap();
  const picker=page.locator('.recipe-picker-modal');
  await shot('05-source',picker);
  await picker.locator('[data-recipe-id="'+fixture.recipe+'"]').tap();
  await shot('02-recipe');
  await shot('04-basic',modal.locator('.batch-basic'));
  await shot('long-320');
  await modal.locator('.batch-review > summary').tap();
  const row=modal.locator('.draft-ingredient').first();
  const quantity=row.locator('input');
  await quantity.tap();
  await shot('07-quantity',row);
  await quantity.press('Enter');
  await row.locator('.draft-unit-trigger').tap();
  const menu=modal.locator('.draft-unit-menu');
  await expect(menu.getByRole('menuitemradio')).toHaveCount(2);
  await shot('08-units');
  await menu.locator('[data-unit="勺"]').tap();
  await expect(quantity).toHaveValue('4');
  await modal.locator('.storage-add-source').tap();
  await page.locator('.stored-food-picker .storage-list-row').tap();
  const remaining=()=>page.evaluate(async id=>(await(await import('/src/domain.ts')).db.foodBatches.get(id))!.remainingQuantity,fixture.stock);
  expect(await remaining()).toBe(350);
  await shot('06-ingredients',modal.locator('.batch-review'));
  await weight.fill('400');
  expect((await ink.boundingBox())!.width).toBe(56);
  await shot('10-weight-edit',weightSection);
  await weight.press('Enter');
  expect((await ink.boundingBox())!.width).toBe(56);
  const summaries=modal.locator('.storage-batch-nutrition');
  await expect(summaries.locator('input,button,select,.journal-amount-ink')).toHaveCount(0);
  await shot('11-whole',summaries.first());
  await shot('12-per100',summaries.last());
  await modal.locator('.storage-make-scroll').evaluate(el=>el.scrollTop=0);
  await shot('03-filled');
  await shot('results-calculated',weightSection);
  await modal.locator('.batch-note-action').tap();
  await modal.locator('textarea').fill('留作周末早餐。');
  await modal.locator('textarea').press('Tab');
  await modal.locator('.form-actions .primary').tap();
  await expect(modal).toHaveCount(0);
  expect(await remaining()).toBeLessThan(350);
  await page.locator('.storage-list-row').filter({hasText:'Apple Cinnamon'}).tap();
  await page.getByRole('button',{name:language==='zh'?'修正配方':'Correct formula',exact:true}).tap();
  await expect(weight).toHaveValue('400');
  await expect(headings).toHaveCount(1);
  await expect(modal.locator('.batch-note-text')).toHaveText('留作周末早餐。');
  await shot('existing-note',modal.locator('.batch-results'));
  await modal.locator('.storage-make-scroll').evaluate(el=>el.scrollTop=0);
  await shot('13-correct');
  await weight.fill('500');
  await modal.locator('.form-actions button').first().tap();
  expect(await page.evaluate(async()=>{const d=await import('/src/domain.ts');return (await d.db.foodBatches.toArray()).find(b=>b.name.includes('Apple Cinnamon'))!.originalCookedYield})).toBe(400);
});
