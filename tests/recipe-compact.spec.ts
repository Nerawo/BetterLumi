import { test, expect } from '@playwright/test';
const output='./work/screenshots/';
for(const width of [320,360,390]) {
 test(`saved recipe is compact, optional edits stay closed and snapshots remain separate at ${width}px`,async({page})=>{
  await page.setViewportSize({width,height:844});
  await page.goto('/today');
  const ids=await page.evaluate(async()=>{
   const d=await import('/src/domain.ts');
   const ingredient={...d.stamp(),name:'长名称燕麦测试食材',nameZh:'',brand:'',basis:'100g',servingGrams:null,calories:400,protein:10,carbs:70,fat:8};
   await d.db.ingredients.put(ingredient);
   const recipe={...d.stamp(),name:'燕麦早餐',servings:2,lines:[{ingredientId:ingredient.id,name:ingredient.name,quantity:100,unit:'g',nutrition:{calories:400,protein:10,carbs:70,fat:8}}],instructions:'煮熟',stickyNote:'保持原食谱'};
   const other={...recipe,...d.stamp(),name:'另一份食谱'};
   await d.recipes.bulkPut([recipe,other]);return {recipe:recipe.id,other:other.id,ingredient:ingredient.id};
  });
  await page.getByRole('button',{name:'添加餐食',exact:true}).click();
  const modal=page.locator('.add-food-modal');
  await modal.locator('.source-tabs button').first().click();
  await modal.locator('.add-food-scroll > label select').selectOption(ids.recipe);
  const advanced=modal.locator('.meal-advanced');
  await expect(advanced).not.toHaveAttribute('open');
  await expect(modal.locator('input:not([type])')).toHaveCount(0);
  await expect(modal.locator('.source-tabs button')).toHaveCount(3);
  await expect(modal).not.toContainText('截图');
  const stepper=modal.locator('.recipe-serving-input');
  await expect(stepper).toBeVisible();
  expect(await stepper.evaluate(e=>e.scrollWidth<=e.clientWidth)).toBe(true);
  const dates=await modal.locator('.meal-date-row label').evaluateAll(nodes=>nodes.map(n=>n.getBoundingClientRect().y));expect(dates[0]).toBe(dates[1]);
  await expect(modal.locator('.add-food-footer .primary')).toBeInViewport();
  await page.screenshot({path:output+`食谱记录-${width}px-默认.png`});
  await advanced.locator('summary').click();
  await expect(advanced).toHaveAttribute('open','');
  await modal.locator('.add-food-scroll > label select').selectOption(ids.other);
  await expect(advanced).not.toHaveAttribute('open');
  await modal.locator('.add-food-scroll > label select').selectOption(ids.recipe);
  await expect(advanced).not.toHaveAttribute('open');
  await modal.locator('.recipe-amounts input[type=number]').first().fill('2');
  await modal.getByRole('slider').press('Home');for(let value=0;value<50;value+=5)await modal.getByRole('slider').press('ArrowRight');
  await expect(modal.locator('.meal-nutrition-preview .nutrition-strip > div').first()).toContainText('200');
  await modal.locator('.recipe-rename button').click();
  await modal.locator('.recipe-rename input').fill('本次早餐');
  await advanced.locator('summary').click();
  const row=advanced.locator('.recipe-line');
  await expect(row.locator('.replace-select')).toHaveCount(0);
  await row.locator('input').fill('60');
  await expect(modal.locator('.meal-nutrition-preview .nutrition-strip > div').first()).toContainText('120');
  await row.locator('.ingredient-replace-toggle').click();
  await expect(page.locator('.ingredient-picker-modal')).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(page.locator('.ingredient-picker-modal')).toHaveCount(0);
  await expect(row.locator('input')).toHaveValue('60');
  expect(await modal.evaluate(e=>e.scrollWidth<=e.clientWidth)).toBe(true);
  const geometry=await row.evaluate(e=>({height:e.getBoundingClientRect().height,input:e.querySelector('input')!.getBoundingClientRect().height}));
  const layout=await row.evaluate(e=>{const heading=e.querySelector('.recipe-line-heading')!.getBoundingClientRect(),amounts=e.querySelector('.recipe-line-amounts')!.getBoundingClientRect();return {heading:heading.bottom,amounts:amounts.top,width:e.clientWidth,scroll:e.scrollWidth}});
  expect(layout.amounts).toBeGreaterThanOrEqual(layout.heading-1);
  expect(layout.scroll).toBeLessThanOrEqual(layout.width);
  expect(geometry.input).toBeGreaterThanOrEqual(44);
  await row.scrollIntoViewIfNeeded();
  await page.screenshot({path:output+`食谱记录-${width}px-展开.png`});
  await row.locator('select').first().selectOption('serving');
  await expect(modal.locator('.meal-nutrition-preview .nutrition-strip > div').first()).toContainText('未记录');
  await row.locator('select').first().selectOption('g');
  await expect(row.locator('input')).toHaveValue('100');
  await row.locator('input').fill('60');
  await expect(modal.locator('.meal-nutrition-preview .nutrition-strip > div').first()).toContainText('120');
  await advanced.locator('.line-add button').click();
  await page.locator(`.ingredient-picker-modal [data-ingredient-id="${ids.ingredient}"]`).click();
  await expect(advanced.locator('.recipe-line')).toHaveCount(2);
  await advanced.locator('.recipe-line').last().getByRole('button',{name:/删除/}).click();
  await expect(advanced.locator('.recipe-line')).toHaveCount(1);
  await expect(modal.locator('.meal-nutrition-preview .nutrition-strip > div').first()).toContainText('120');
  await page.setViewportSize({width,height:460});
  await expect(modal.locator('.add-food-footer .primary')).toBeInViewport();
  await modal.locator('.add-food-footer .primary').click();
  await expect(modal).toHaveCount(0);
  const saved=await page.evaluate(async id=>{const d=await import('/src/domain.ts');return {original:await d.recipes.get(id),logs:await d.foodLogs.toArray()}},ids.recipe);
  expect(saved.original!.lines[0].quantity).toBe(100);
  expect(saved.logs[0].lines[0].quantity).toBe(60);
  expect(saved.logs[0].name).toBe('本次早餐');
  expect(saved.logs[0].nutrition.calories).toBe(120);
  await page.reload();
  await page.locator('.meal-row').getByRole('button',{name:'编辑',exact:true}).click();
  await expect(modal.locator('.meal-advanced')).not.toHaveAttribute('open');
  await expect(modal.locator('.recipe-rename')).toContainText('重命名');
 });
}
